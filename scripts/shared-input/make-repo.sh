#!/usr/bin/env bash
# A small Convex-shaped vitest project as a git repo whose commits are the
# cases of the "over-broad shared input" experiment (class-management run
# 41605004207: a new convex/lib file re-ran all 106 backend test files,
# "shared input changed: d:convex/lib").
#
#   make-repo.sh <dir>        then: shadow.sh <dir> HEAD 7 run
#
# tests/helpers.ts holds convex-test's pattern, import.meta.glob over
# ../convex/**/*.ts (lazy); most test files import it and call a function
# through it. tests/pure-*.test.ts import convex/lib directly (no glob).
# tests/contract.test.ts globs eagerly. tests/registry.test.ts asserts how
# many lib modules the glob found (a test a new lib file really changes).
# convex/_generated/api.d.ts is imported only as a type.
#
# Commits after the base:
#   1 docs only                         (everything replays)
#   2 add convex/lib/closures.ts        (PR #277's shape; registry.test fails)
#   3 type-only: _generated/api.d.ts    (the .d.ts suspect)
#   4 registry.test expects 6 lib files (a test file changes)
#   5 add convex/notices.ts             (new top-level module)
#   6 runtime: lib/money.ts rounds down (breaks the tests that use it)
#   7 revert money.ts
set -euo pipefail
d=$1
rm -rf "$d"; mkdir -p "$d"; cd "$d"
git init -q -b main
git config user.email bench@example.com; git config user.name bench
mkdir -p convex/lib convex/_generated tests
cat > package.json <<'J'
{
  "name": "convex-shaped",
  "private": true,
  "type": "module",
  "devDependencies": { "vitest": "4.1.11", "vite": "8.3.4" }
}
J
printf 'node_modules\npackage-lock.json\n' > .gitignore
cat > vitest.config.ts <<'J'
import { defineConfig } from 'vitest/config'
export default defineConfig({ test: { include: ['tests/**/*.test.ts'], environment: 'node' } })
J
echo '# convex-shaped' > README.md
libs=(money ages schedule roster bills)
for l in "${libs[@]}"; do
  cat > convex/lib/$l.ts <<J
// $l helpers
export function ${l}Value(n: number): number {
  return Math.round(n * 100) / 100 + ${#l}
}
export const ${l}Name = '$l'
J
done
cat > convex/lib/money.ts <<'J'
export function moneyValue(n: number): number {
  return Math.round(n * 100) / 100
}
export function format(cents: number): string {
  return `$${(Math.round(cents) / 100).toFixed(2)}`
}
export const moneyName = 'money'
J
for f in families lessons payments; do
  cat > convex/$f.ts <<J
import { moneyValue } from './lib/money'
import { schedulesValue } from './lib/scheduleAlias'
export function ${f}Total(xs: number[]): number {
  return xs.reduce((a, x) => a + moneyValue(x), 0) + schedulesValue()
}
J
done
cat > convex/lib/scheduleAlias.ts <<'J'
import { scheduleValue } from './schedule'
export const schedulesValue = () => scheduleValue(0) - 8
J
cat > convex/_generated/api.d.ts <<'J'
/* Generated by the backend's codegen (shape only). */
export type Api = {
  families: { familiesTotal: (xs: number[]) => number }
  lessons: { lessonsTotal: (xs: number[]) => number }
  payments: { paymentsTotal: (xs: number[]) => number }
}
export declare const api: Api
J
cat > tests/helpers.ts <<'J'
import type { Api } from '../convex/_generated/api'
// convex-test's pattern: every backend module, by path, loaded on demand.
export const modules = import.meta.glob('../convex/**/*.ts')
export async function call<M extends keyof Api, F extends keyof Api[M]>(mod: M, fn: F, ...args: unknown[]): Promise<number> {
  const m = (await modules[`../convex/${String(mod)}.ts`]()) as Record<string, (...a: unknown[]) => number>
  return m[fn as string](...args)
}
export function work(ms: number) {
  const t = performance.now()
  let x = 0
  while (performance.now() - t < ms) x++
  return x
}
J
n=0
for mod in families lessons payments; do
  for k in 1 2 3 4 5 6; do
    n=$((n + 1))
    cat > tests/h$(printf %02d $n)-$mod.test.ts <<J
import { expect, test } from 'vitest'
import { call, work } from './helpers'
test('$mod total $k', async () => {
  work(300)
  expect(await call('$mod', '${mod}Total', [1.257, $k])).toBeCloseTo(1.26 + $k, 5)
})
J
  done
done
for l in "${libs[@]}"; do
  cat > tests/pure-$l.test.ts <<J
import { expect, test } from 'vitest'
import { ${l}Value } from '../convex/lib/$l'
import { work } from './helpers-free'
test('$l value', () => {
  work(300)
  expect(${l}Value(2)).toBeGreaterThan(1)
})
J
done
cat >> tests/pure-money.test.ts <<'J'
import { format } from '../convex/lib/money'
test('format', () => {
  expect(format(199.6)).toBe('$2.00')
  expect(moneyValue(1.257)).toBe(1.26)
})
J
cat > tests/helpers-free.ts <<'J'
export function work(ms: number) {
  const t = performance.now()
  let x = 0
  while (performance.now() - t < ms) x++
  return x
}
J
cat > tests/registry.test.ts <<'J'
import { expect, test } from 'vitest'
import { modules } from './helpers'
test('the backend has five lib modules besides the alias', () => {
  const libs = Object.keys(modules).filter((k) => k.includes('/lib/') && !k.endsWith('Alias.ts'))
  expect(libs.length).toBe(5)
})
J
cat > tests/contract.test.ts <<'J'
import { expect, test } from 'vitest'
const all = import.meta.glob<Record<string, unknown>>(['../convex/**/*.ts', '!../convex/**/*.d.ts'], { eager: true })
test('every module exports only functions and strings', () => {
  for (const [p, m] of Object.entries(all)) {
    for (const [k, v] of Object.entries(m)) expect(['function', 'string'], `${p} ${k}`).toContain(typeof v)
  }
})
J
git add -A; git commit -qm 'base: convex-shaped backend, helpers glob'
echo 'Run `npx vitest run`.' >> README.md
git commit -qam 'docs only'
cat > convex/lib/closures.ts <<'J'
// closures per location (PR #277's new lib file)
export function closuresValue(n: number): number {
  return n + 1
}
J
git add -A; git commit -qm 'add convex/lib/closures.ts'
sed -i.bak 's/payments: { paymentsTotal: (xs: number\[\]) => number }/payments: { paymentsTotal: (xs: number[]) => number; refund?: (id: string) => void }/' convex/_generated/api.d.ts; rm -f convex/_generated/api.d.ts.bak
git commit -qam 'type-only: convex/_generated/api.d.ts'
sed -i.bak 's/five lib modules/six lib modules/; s/toBe(5)/toBe(6)/' tests/registry.test.ts; rm -f tests/registry.test.ts.bak
git commit -qam 'registry test expects six lib modules'
cat > convex/notices.ts <<'J'
export function noticesCount(xs: string[]): number {
  return xs.length
}
J
git add -A; git commit -qm 'add convex/notices.ts'
sed -i.bak 's|return Math.round(n \* 100) / 100$|return Math.floor(n * 100) / 100|' convex/lib/money.ts; rm -f convex/lib/money.ts.bak
grep -q Math.floor convex/lib/money.ts
git commit -qam 'runtime: money rounds down'
git revert --no-edit HEAD >/dev/null
git log --oneline | cat
